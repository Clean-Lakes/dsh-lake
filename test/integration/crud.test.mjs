import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { once } from 'node:events';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { apply } from '../../lib/index.js';

test('workspace CRUD uses real Lake mutations, preserves credentials and children, and refuses cross-workspace/online changes', {timeout:45000}, async t=>{
  const home=await mkdtemp(join(tmpdir(),'dsh-lake-crud-')),effects=[],routes=[];
  const ctx={effect:fn=>{const off=fn();if(typeof off==='function')effects.push(off);},inject:(deps,fn)=>{if(!deps.includes('tools'))fn(ctx);},get:()=>({requestRejection:()=>undefined}),webServer:{register:route=>{routes.push(route);return()=>{};}}};
  const runtime=apply(ctx,{home});
  const server=http.createServer((req,res)=>{const route=routes.find(r=>r.kind==='prefix'&&req.url.startsWith(r.path+'/'));if(route)void route.handler(req,res);else{res.writeHead(404);res.end();}});
  server.listen(0,'127.0.0.1');await once(server,'listening');
  t.after(async()=>{server.closeAllConnections();server.close();for(const off of effects.reverse())await off();await rm(home,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/lake/api`;
  async function api(path,method='GET',data,status=200){const reply=await fetch(base+path,{method,headers:{'Content-Type':'application/json'},...(data===undefined?{}:{body:JSON.stringify(data)})});const result=await reply.json();assert.equal(reply.status,status,`${method} ${path}: ${JSON.stringify(result)}`);return result;}
  const group=await api('/workspaces/one/resources','POST',{name:'CRUD fixture'});
  await api('/workspaces/two/resources','POST',{name:'Other fixture'});
  const tree=(data,status=200)=>api('/workspaces/one/resource-tree','POST',data,status);
  let nodes=(await tree({operation:'create',name:'Parent'})).nodes;
  const parent=nodes.find(n=>n.kind==='folder').id;
  nodes=(await tree({operation:'create',name:'Child',parentId:parent})).nodes;
  const child=nodes.find(n=>n.name==='Child').id;
  await tree({operation:'rename',nodeId:parent,name:'Renamed parent'});
  await tree({operation:'move',nodeId:parent,parentId:child},400);
  await api('/workspaces/two/resource-tree','POST',{operation:'delete',nodeId:parent},404);
  await api('/workspaces/two/resource-tree','POST',{operation:'create',name:'Foreign folder',parentId:parent},404);
  const host=await api('/workspaces/one/resource-items','POST',{name:'SSH fixture',kind:'ssh',parentId:child,ssh:{host:'192.0.2.1',port:22,username:'fixture',authMethod:'password',password:'synthetic-crud-secret'}},201);
  const hostPath='/workspaces/one/resource-items/'+host.id;
  assert.equal((await api(hostPath)).ssh.host,'192.0.2.1');
  const secretRef=host.ssh.credentialRef;
  const updated=await api(hostPath,'PATCH',{name:'Renamed SSH',ssh:{host:'192.0.2.2',password:''}});
  assert.equal(updated.ssh.credentialRef,secretRef);assert.equal(updated.ssh.host,'192.0.2.2');
  assert.equal(await readFile(join(home,'secrets',secretRef),'utf8'),'synthetic-crud-secret');
  await api(hostPath,'PATCH',{name:'Bad ref',ssh:{credentialRef:'foreign-secret'}},400);
  await api(hostPath,'PATCH',{name:'Bad config',ssh:'not-object'},400);
  await api('/workspaces/two/resource-items/'+host.id,'PATCH',{name:'Wrong workspace'},404);
  await api('/workspaces/two/resource-items/'+host.id,'DELETE',undefined,404);
  const hostNode=(await api('/workspaces/one/resources')).resourceTree.find(n=>n.resourceId===host.id).id;
  await tree({operation:'move',nodeId:hostNode,parentId:parent});
  assert.equal((await api('/workspaces/one/resources')).resourceTree.find(n=>n.resourceId===host.id).parentId,parent);
  await tree({operation:'move',nodeId:hostNode,parentId:child});
  await tree({operation:'delete',nodeId:child});
  assert.equal((await api('/workspaces/one/resources')).resourceTree.find(n=>n.resourceId===host.id).parentId,parent);
  await tree({operation:'delete',nodeId:parent});
  assert.equal((await api('/workspaces/one/resources')).resourceTree.find(n=>n.resourceId===host.id).parentId,null);
  const local=(await api('/workspaces/one/resources')).resources.find(r=>r.kind==='local');
  const localPath='/workspaces/one/resource-items/'+local.id;
  const {terminal}=await api('/terminals/open','POST',{dshSessionId:'crud-terminal',resourceId:local.id},201);
  assert.equal((await api(localPath,'PATCH',{name:'Renamed local'})).name,'Renamed local');
  await api(localPath,'PATCH',{name:'Renamed local',settings:{shell:'zsh'}},409);
  await api(localPath,'DELETE',undefined,409);
  await tree({operation:'create',name:'Destination'});
  const destination=(await api('/workspaces/one/resources')).resourceTree.find(n=>n.name==='Destination');
  await tree({operation:'move',nodeId:local.id,parentId:destination.id},400);
  await api('/terminals/'+terminal.id+'/disconnect','POST',{dshSessionId:'crud-terminal',projectId:group.id});
  assert.equal((await api(localPath,'PATCH',{name:'Renamed local',settings:{shell:'sh'}})).settings.shell,'sh');
  await api(hostPath,'DELETE');
  await api(hostPath,'GET',undefined,404);
  assert.ok(!(await api('/workspaces/one/resources')).resources.some(r=>r.id===host.id));
  const trash=await new (await import('../../lib/backend.js')).LakeBackend(runtime).call('/navigation-trash');
  assert.ok(trash.items.some(item=>item.kind==='resource'&&item.id===host.id));
  assert.ok(trash.items.some(item=>item.kind==='folder'&&item.id===parent));
});
